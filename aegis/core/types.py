"""
AegisLLM Core - Types & Security Data Models
Defines OWASP LLM categories, vulnerability severity, attack payloads, and security report schemas.
"""

from __future__ import annotations
from enum import Enum
import time
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class OWASPCategory(str, Enum):
    LLM01_PROMPT_INJECTION = "LLM01: Prompt Injection"
    LLM02_SENSITIVE_INFO_DISCLOSURE = "LLM02: Sensitive Information Disclosure"
    LLM04_MODEL_DOS = "LLM04: Model Denial of Service"
    LLM07_SYSTEM_PROMPT_LEAKAGE = "LLM07: System Prompt Leakage"


class Severity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class AttackCategory(str, Enum):
    PROMPT_INJECTION = "prompt_injection"
    JAILBREAK = "jailbreak"
    SYSTEM_LEAK = "system_leak"
    CANARY_PROBE = "canary_probe"
    DENIAL_OF_SERVICE = "dos"


class AttackPayload(BaseModel):
    """Represents an adversarial payload sent to the target LLM."""
    id: str = Field(..., description="Unique payload ID")
    name: str = Field(..., description="Human-readable attack technique name")
    category: AttackCategory = Field(..., description="Attack category")
    owasp: OWASPCategory = Field(..., description="Mapped OWASP LLM category")
    prompt: str = Field(..., description="The adversarial prompt text")
    description: str = Field(..., description="Technique rationale and goal")
    canary_token: Optional[str] = Field(None, description="Optional canary token to look for")
    mutations_applied: List[str] = Field(default_factory=list, description="List of mutations applied")


class AttackResult(BaseModel):
    """Evaluation result of an executed attack payload."""
    payload: AttackPayload
    response_text: str = Field(..., description="Raw output generated by target LLM")
    is_vulnerable: bool = Field(..., description="True if target succumbed to the exploit")
    severity: Severity = Field(..., description="Vulnerability severity if exploited")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Detection confidence score")
    explanation: str = Field(..., description="Detailed vulnerability finding explanation")
    latency_ms: float = Field(..., description="Response latency in milliseconds")
    timestamp: float = Field(default_factory=time.time)


class VulnerabilityItem(BaseModel):
    name: str
    category: AttackCategory
    owasp: OWASPCategory
    severity: Severity
    prompt_used: str
    response_sample: str
    explanation: str


class SecurityScorecard(BaseModel):
    target_name: str
    total_probes: int
    successful_exploits: int
    attack_success_rate_pct: float
    grade: str  # A+, A, B, C, D, F
    severity_breakdown: Dict[str, int]
    owasp_breakdown: Dict[str, int]
    vulnerabilities: List[VulnerabilityItem]
    scan_duration_seconds: float
    timestamp: float = Field(default_factory=time.time)
